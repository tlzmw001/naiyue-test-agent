"""Observation interfaces shared by runtime and tools, without runtime imports."""

from typing import Protocol


class RunPublisher(Protocol):
    @property
    def run_id(self) -> str: ...
    def matches(self, session_id, run_id) -> bool: ...
    def publish(self, event_type, data): ...


class MessageObservation(Protocol):
    publisher: RunPublisher
    def observe(self, messages, *, visibility='graph_values'): ...


class TurnObservation(MessageObservation, Protocol):
    def begin(self, model_call_id): ...
    def accept(self, message): ...
    def mark_ready(self): ...
    def try_finish(self): ...
    def result(self, *, interrupted): ...
    def fail(self, failure): ...
    def disable(self, reason='state_observation_unavailable'): ...
    def snapshot(self, *, pending): ...
    def restore(self, saved): ...
    def activate_resume(self, baseline): ...


class ControlObservation(MessageObservation, Protocol):
    def start(self): ...
    def accept(self, kind, *, queue_size=0, tool_call_ids=(), decisions=(), origin_run_id=None): ...
    def select(self, kind, count): ...
    def record_messages(self, messages): ...
    def submit_approval(self): ...
    def begin_approval_hook(self): ...
    def note_approval_candidate(self, tool_call_id): ...
    def approval_applied(self): ...
    def run_result(self, result): ...
    def approval_requested(self, tool_call_ids, approval_batch_id=None, items=()): ...
    def close(self, reason): ...
    def flush(self): ...


class ContextOperationObservation(MessageObservation, Protocol):
    def model_call_started(self, call_id): ...
    def begin_compaction(self, model_id, trigger, estimate, count): ...
    def summary_started(self, op): ...
    def summary_finished(self, op, duration_ms, usage=None, error=None): ...
    def prepare_compaction(self, op, summary, preserved, removed, estimate): ...
    def finish_compaction(self, op, status, reason=None, error=None): ...
    def begin_recovery(self, model_id): ...
    def retry_started(self, op): ...
    def retry_returned(self, op, response): ...
    def fail_recovery(self, op, stage, error): ...
    def model_call_accepted(self, call_id): ...
    def model_call_failed(self, call_id, error): ...
    def finalize(self, error=None): ...
    def flush(self): ...


class ToolProgressObservation(Protocol):
    publisher: RunPublisher
    _diagnosed: bool
    def begin_dispatch(self, request): ...
    def report_dispatch(self, request, activity): ...
    def accept_custom(self, payload): ...
    def finish(self, batch_id, call_id): ...
